/**
 * The generated reference cannot drift: the generator's output is compared with the committed files, byte for byte.
 * If this fails, run `npm run docs:reference` and commit the result.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { Provider } from '../../src/constants.js';
import { EnvVar } from '../../src/service-config.js';
import { GENERATED_PATHS, PROVIDERS, PROVIDERS_WITHOUT_ADAPTER, generateAll } from '../../scripts/generate-docs-reference.js';
import { DOCS } from './lib.js';

const generated = generateAll();

describe('generated reference', () => {
  it('matches the committed files', () => {
    for (const [path, content] of generated) {
      const committed = readFileSync(join(DOCS, path), 'utf8');
      expect(committed === content, `${path} differs from the generator's output: run npm run docs:reference`).toBe(true);
    }
  });

  it('covers every generated page, and each carries the do-not-edit header', () => {
    for (const path of GENERATED_PATHS) {
      const content = generated.get(path);
      expect(content, path).toBeDefined();
      expect(content).toContain('GENERATED FILE: do not edit');
      expect(content).toContain('Do not edit this file');
    }
  });

  it('documents every model and route the service publishes', () => {
    const models = generated.get('reference/generated/models.md') ?? '';
    for (const name of ['Subscription', 'CreateSubscriptionInput', 'Charge', 'Refund', 'Capabilities', 'SubscriptionEvent', 'ErrorResponse', 'TickResult']) {
      expect(models).toContain(`### ${name}\n`);
    }
    const api = generated.get('reference/generated/http-api.md') ?? '';
    for (const operation of ['createSubscription', 'verifyCheckout', 'receiveWebhook', 'runSchedulerTick']) expect(api).toContain(`### ${operation}\n`);
  });

  it('lists every environment variable the service reads', () => {
    const environment = generated.get('reference/generated/environment.md') ?? '';
    for (const name of Object.values(EnvVar)) expect(environment).toContain(`\`${name}\``);
  });

  it('puts every gateway with an adapter in the capability matrix, and every other gateway on a stub page', () => {
    const capabilities = generated.get('reference/generated/capabilities.md') ?? '';
    expect(PROVIDERS.length).toBeGreaterThan(0);
    for (const provider of PROVIDERS) {
      const page = readFileSync(join(DOCS, 'gateways', `${provider}.md`), 'utf8');
      expect(page).toContain(`<!-- generated:begin capabilities ${provider} -->`);
    }
    for (const provider of PROVIDERS_WITHOUT_ADAPTER) {
      const page = readFileSync(join(DOCS, 'gateways', `${provider}.md`), 'utf8');
      expect(page, `${provider} has no adapter, so its page is a stub`).toContain('In progress');
      expect(capabilities).not.toContain(`| ${provider}`);
    }
    expect([...PROVIDERS, ...PROVIDERS_WITHOUT_ADAPTER].sort()).toEqual(Object.values(Provider).sort());
  });

  it('shows the gateway mapping tables inside the gateway pages', () => {
    const razorpay = generated.get('gateways/razorpay.md') ?? '';
    expect(razorpay).toContain('| `authenticated` | `trialing` |');
    const cashfree = generated.get('gateways/cashfree.md') ?? '';
    expect(cashfree).toContain('| `BANK_APPROVAL_PENDING` | `pending_authorization` |');
    const payu = generated.get('gateways/payu.md') ?? '';
    expect(payu).toContain('| `in progress` | `pending` |');
  });
});
